CREATE OR REPLACE TABLE DIM_DATE (
    DATE_KEY          NUMBER(8,0)  NOT NULL,   -- YYYYMMDD
    FULL_DATE         DATE         NOT NULL,
    DATE_NAME         VARCHAR(10)  NOT NULL,   -- 2025-03-14
    DAY_OF_WEEK_NAME  VARCHAR(3)   NOT NULL,   -- Fri
    MONTH_KEY         NUMBER(6,0)  NOT NULL,   -- YYYYMM
    MONTH_NAME        VARCHAR(8)   NOT NULL,   -- Mar 2025
    MONTH_OF_YEAR     NUMBER(2,0)  NOT NULL,
    QUARTER_KEY       NUMBER(5,0)  NOT NULL,   -- YYYYQ
    QUARTER_NAME      VARCHAR(7)   NOT NULL,   -- Q1 2025
    QUARTER_OF_YEAR   NUMBER(1,0)  NOT NULL,
    YEAR_NUM          NUMBER(4,0)  NOT NULL,
    YEAR_NAME         VARCHAR(4)   NOT NULL,
    CONSTRAINT PK_DIM_DATE PRIMARY KEY (DATE_KEY)
);

CREATE OR REPLACE TABLE DIM_CUSTOMER (
    CUSTOMER_ID       NUMBER(10,0) NOT NULL,
    CUSTOMER_NAME     VARCHAR(100) NOT NULL,
    CUSTOMER_SEGMENT  VARCHAR(20)  NOT NULL,   -- Enterprise / Mid-Market / SMB
    COUNTRY           VARCHAR(50)  NOT NULL,
    REGION            VARCHAR(30)  NOT NULL,
    CONSTRAINT PK_DIM_CUSTOMER PRIMARY KEY (CUSTOMER_ID)
);

CREATE OR REPLACE TABLE DIM_PRODUCT (
    PRODUCT_ID        NUMBER(10,0) NOT NULL,
    SKU               VARCHAR(20)  NOT NULL,
    PRODUCT_NAME      VARCHAR(100) NOT NULL,
    CATEGORY          VARCHAR(50)  NOT NULL,
    LIST_PRICE        NUMBER(12,2) NOT NULL,
    UNIT_COST         NUMBER(12,2) NOT NULL,
    CONSTRAINT PK_DIM_PRODUCT PRIMARY KEY (PRODUCT_ID)
);

CREATE OR REPLACE TABLE FACT_SALES (
    ORDER_ID          VARCHAR(12)  NOT NULL,   -- SO-000123
    ORDER_LINE        NUMBER(3,0)  NOT NULL,
    ORDER_DATE_KEY    NUMBER(8,0)  NOT NULL,
    CUSTOMER_ID       NUMBER(10,0) NOT NULL,
    PRODUCT_ID        NUMBER(10,0) NOT NULL,
    QUANTITY          NUMBER(6,0)  NOT NULL,
    UNIT_PRICE        NUMBER(12,2) NOT NULL,
    DISCOUNT_PCT      NUMBER(5,4)  NOT NULL,
    DISCOUNT_AMOUNT   NUMBER(14,2) NOT NULL,
    SALES_AMOUNT      NUMBER(14,2) NOT NULL,
    COST_AMOUNT       NUMBER(14,2) NOT NULL,
    CONSTRAINT PK_FACT_SALES PRIMARY KEY (ORDER_ID, ORDER_LINE),
    CONSTRAINT FK_SALES_DATE     FOREIGN KEY (ORDER_DATE_KEY) REFERENCES DIM_DATE (DATE_KEY),
    CONSTRAINT FK_SALES_CUSTOMER FOREIGN KEY (CUSTOMER_ID)    REFERENCES DIM_CUSTOMER (CUSTOMER_ID),
    CONSTRAINT FK_SALES_PRODUCT  FOREIGN KEY (PRODUCT_ID)     REFERENCES DIM_PRODUCT (PRODUCT_ID)
);
